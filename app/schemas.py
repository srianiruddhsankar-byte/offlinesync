"""Pydantic models for request envelopes."""

import uuid
from typing import Any, Literal, Self

from pydantic import BaseModel, Field, field_validator, model_validator

from .merge import SQLITE_INT_MAX


class SyncRequest(BaseModel):
    request_id: str = Field(
        description="UUID chosen by the client. Retrying with the same id is safe (idempotent)."
    )
    device_id: str = Field(pattern=r"^[A-Za-z0-9_-]{1,64}$", description="Self-declared device identifier.")
    sequence: int = Field(ge=1, le=SQLITE_INT_MAX, description="Per-device operation counter, starting at 1.")
    record_id: str = Field(description="UUID of the record, generated by the client.")
    op: Literal["create", "update", "delete"]
    base_version: int = Field(
        ge=0, le=SQLITE_INT_MAX, description="Record version the device last saw (0 for create)."
    )
    partial: bool = Field(
        default=False, description="Apply non-conflicting fields of an update and report the rest."
    )
    changes: dict[str, dict[str, Any]] = Field(default_factory=dict)

    @field_validator("request_id", "record_id")
    @classmethod
    def _uuid(cls, v: str) -> str:
        try:
            return str(uuid.UUID(v))
        except ValueError:
            raise ValueError("must be a valid UUID") from None

    @model_validator(mode="after")
    def _base_rules(self) -> Self:
        if self.op == "create" and self.base_version != 0:
            raise ValueError("create requires base_version 0")
        if self.op in ("update", "delete") and self.base_version < 1:
            raise ValueError(f"{self.op} requires base_version >= 1")
        return self


class BatchRequest(BaseModel):
    changes: list[SyncRequest] = Field(min_length=1, max_length=100)


class RestoreRequest(BaseModel):
    request_id: str = Field(description="UUID chosen by the client (idempotency key).")
    device_id: str = Field(pattern=r"^[A-Za-z0-9_-]{1,64}$")
    base_version: int = Field(
        ge=1, le=SQLITE_INT_MAX, description="Current version the device last saw. A stale value is a 409."
    )

    @field_validator("request_id")
    @classmethod
    def _uuid(cls, v: str) -> str:
        try:
            return str(uuid.UUID(v))
        except ValueError:
            raise ValueError("must be a valid UUID") from None
